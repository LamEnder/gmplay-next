#!/usr/bin/env python3
"""Rasterize a TTF into src/font_data.c (8-bit alpha glyphs, ASCII 32..126).

    usage: tools/gen_font.py [font.ttf] > src/font_data.c

Default font is DejaVu Sans (Bitstream Vera license, permissive).
Needs Pillow on the build host (apt install python3-pil).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

SIZES = {"FONT_SMALL": 34, "FONT_LARGE": 46}   # px; PW4 is 300 dpi
FIRST, LAST = 32, 126
path = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"

out = ["// Generated by tools/gen_font.py from %s - do not edit." % path.rsplit("/", 1)[-1],
       '#include "font.h"', ""]

for name, px in SIZES.items():
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    for c in range(FIRST, LAST + 1):
        ch = chr(c)
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")   # relative to baseline
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bits)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            bits += img.tobytes()
        glyphs.append((adv, w, h, x0, y0, off))
    lname = name.lower()
    out.append("static const uint8_t %s_bits[%d] = {" % (lname, max(1, len(bits))))
    for i in range(0, len(bits), 24):
        out.append("    " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
    out.append("};")
    out.append("static const Glyph %s_glyphs[%d] = {" % (lname, LAST - FIRST + 1))
    for c, g in zip(range(FIRST, LAST + 1), glyphs):
        out.append("    {%d,%d,%d,%d,%d,%u},  // %r" % (*g, chr(c)))
    out.append("};")
    out.append("const Font %s = { %d, %d, %d, %s_glyphs, %s_bits };" %
               (lname, ascent, descent, ascent + descent, lname, lname))
    out.append("")

print("\n".join(out))
